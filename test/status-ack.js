'use strict';
const assert = require('assert');
const { EventEmitter } = require('events');
const install = require('../lib/status-ack');
(async () => {
    const ws = new EventEmitter();
    const calls = [], logs = [];
    const sock = { ws, sendMessageAck: async (...args) => calls.push(args) };
    install(sock, (...args) => logs.push(args));
    install(sock);
    assert.strictEqual(ws.listenerCount('CB:status'), 1);
    const node = {tag:'status',attrs:{id:'test',type:'media'},content:[]};
    ws.emit('CB:status',node);
    await new Promise(r => setImmediate(r));
    assert.strictEqual(calls.length,1);
    assert.strictEqual(calls[0][0],node);
    assert.strictEqual(calls[0].length,1, 'must acknowledge without a NACK error code');
    sock.sendMessageAck = async () => { throw new Error('closed'); };
    ws.emit('CB:status',node);
    await new Promise(r => setImmediate(r));
    assert.ok(logs.some(l=>l[0].includes('failed')));
    const native = new EventEmitter();
    native.on('CB:status',()=>{});
    install({ws:native});
    assert.strictEqual(native.listenerCount('CB:status'),1);
    const events = [], encrypted = {...node,content:[{tag:'enc'}]};
    const transport={ws:new EventEmitter(),sendMessageAck:async()=>events.push('ack')};
    install(transport,()=>{},async()=>events.push('process'));
    transport.ws.emit('CB:status',encrypted);
    await new Promise(r=>setImmediate(r));
    assert.deepStrictEqual(events,['process','ack']);
    const failing={ws:new EventEmitter(),sendMessageAck:async()=>events.push('error-ack')};
    install(failing,()=>{},async()=>{throw new Error('decode failed');});
    failing.ws.emit('CB:status',encrypted);
    await new Promise(r=>setImmediate(r));
    assert.strictEqual(events.at(-1),'error-ack');
    console.log('Status transport acknowledgement: 8 passed');
})().catch(err=>{console.error(err);process.exitCode=1;});
