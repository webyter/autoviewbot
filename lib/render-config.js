'use strict';

// lib/render-config.js — generate the Render blueprint (render.yaml).
//
// The blueprint is what Render reads when you create a service from the repo
// (Infrastructure -> Blueprint). Hand-maintaining it drifts: a new env var, a
// changed health path or a wrong cookie setting silently breaks the deploy.
//
// This module renders render.yaml from:
//   - the existing file (name / plan / region / admin contact are preserved),
//   - the local .env (values that belong in the blueprint),
//   - explicit overrides (CLI flags).
//
// SECRETS ARE NEVER WRITTEN: the Groq key, the session secret and the
// invite codes are emitted as `sync: false` placeholders, so Render asks for
// them in the dashboard.
//
// It is used in two places:
//   1. `npm run render:init`  — writes the file locally so it can be committed.
//   2. At startup on Render   — refreshes the file with the PUBLIC_URL the
//      platform reports. (On Render Free the filesystem is ephemeral, so that
//      runtime refresh does NOT survive; it is a convenience + a warning.)

const fs = require('fs');
const path = require('path');

const DEFAULTS = {
    name: 'autoviewer-platform',
    plan: 'free',
    region: 'oregon',
    nodeVersion: '20.18.0',
    adminContact: '233531556024',
    healthCheckPath: '/health',
    keepAliveIntervalMin: '9'
};

function yamlString(value) {
    const s = String(value == null ? '' : value);
    // Quote when the value could be misread as another type.
    if (s === '' || /^[\s]|[\s]$/.test(s)) return JSON.stringify(s);
    if (/^(true|false|null|yes|no|on|off|~)$/i.test(s)) return JSON.stringify(s);
    if (/^[\d.+-]+$/.test(s) && !/^\d+\.\d+$/.test(s)) return JSON.stringify(s);
    if (/[:#{}\[\],&*?|<>=!%@`]/.test(s)) return JSON.stringify(s);
    return s;
}

// Pull a few scalar values out of an existing blueprint so a regeneration
// does not throw away hand-made choices.
function readExisting(file) {
    const out = {};
    try {
        if (!fs.existsSync(file)) return out;
        const src = fs.readFileSync(file, 'utf8');
        // The `m` flag matters: without it `$` only matches the end of the
        // whole file, so values in the middle of the blueprint never match.
        // Values may be quoted in YAML — strip the quotes.
        const pick = (re) => {
            const m = src.match(re);
            if (!m) return undefined;
            return m[1].trim().replace(/^["']|["']$/g, '');
        };
        out.name = pick(/^\s*-?\s*name:\s*(.+)$/m);
        out.plan = pick(/^\s*plan:\s*(.+)$/m);
        out.region = pick(/^\s*region:\s*(.+)$/m);
        out.nodeVersion = pick(/key:\s*NODE_VERSION\s*\n\s*value:\s*(.+)$/m);
        out.adminContact = pick(/key:\s*ADMIN_CONTACT\s*\n\s*value:\s*(.+)$/m);
        out.healthCheckPath = pick(/^\s*healthCheckPath:\s*(.+)$/m);
        out.keepAliveIntervalMin = pick(/key:\s*KEEPALIVE_INTERVAL_MIN\s*\n\s*value:\s*"?([^"\n]+)"?/m);
        return out;
    } catch {
        return out;
    }
}

// Read a value from an env file (first match wins).
function readEnvFile(file) {
    const out = {};
    try {
        if (!fs.existsSync(file)) return out;
        for (const line of fs.readFileSync(file, 'utf8').split('\n')) {
            const m = line.match(/^\s*([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*)$/);
            if (!m) continue;
            const key = m[1];
            if (key in out) continue;
            let val = m[2].trim();
            if ((val.startsWith('"') && val.endsWith('"')) || (val.startsWith("'") && val.endsWith("'"))) val = val.slice(1, -1);
            out[key] = val;
        }
    } catch { /* ignore */ }
    return out;
}

/**
 * Build the blueprint text.
 * @param {object} opts
 *   existing   – parsed values from the current render.yaml
 *   env        – parsed .env values
 *   overrides  – { name, plan, region, publicUrl, adminContact, nodeVersion, keepAliveIntervalMin }
 */
function renderBlueprint(opts = {}) {
    const ex = opts.existing || {};
    const env = opts.env || {};
    const ov = opts.overrides || {};

    const name = ov.name || ex.name || DEFAULTS.name;
    const plan = ov.plan || ex.plan || DEFAULTS.plan;
    const region = ov.region || ex.region || DEFAULTS.region;
    const nodeVersion = ov.nodeVersion || ex.nodeVersion || DEFAULTS.nodeVersion;
    const healthCheckPath = ov.healthCheckPath || ex.healthCheckPath || DEFAULTS.healthCheckPath;
    const adminContact = ov.adminContact || ex.adminContact || env.ADMIN_CONTACT || DEFAULTS.adminContact;
    const keepAlive = String(ov.keepAliveIntervalMin || ex.keepAliveIntervalMin || DEFAULTS.keepAliveIntervalMin);
    const publicUrl = (ov.publicUrl || env.PUBLIC_URL || '').trim();

    const L = [];
    L.push('# Auto-generated by scripts/render-config.js  (npm run render:init)');
    L.push('# Re-generate and commit after changing deploy settings.');
    L.push('services:');
    L.push('  - type: web');
    L.push(`    name: ${yamlString(name)}`);
    L.push('    runtime: node');
    L.push(`    region: ${yamlString(region)}`);
    L.push(`    plan: ${yamlString(plan)}`);
    L.push('    buildCommand: npm ci --omit=dev || npm install --omit=dev');
    L.push('    startCommand: node autoviewer.js');
    L.push(`    healthCheckPath: ${yamlString(healthCheckPath)}`);
    L.push('    autoDeploy: true');
    L.push('    envVars:');
    L.push('      - key: NODE_VERSION');
    L.push(`        value: ${yamlString(nodeVersion)}`);
    L.push('      - key: NODE_ENV');
    L.push('        value: production');
    L.push('      # Render serves HTTPS -> the session cookie must be secure.');
    L.push('      - key: COOKIE_SECURE');
    L.push('        value: "true"');
    L.push('      # Render sets X-Forwarded-Proto; trust one proxy hop.');
    L.push('      - key: TRUST_PROXY');
    L.push('        value: "1"');
    L.push('      # Keep-alive: pings this URL every ~N minutes so the free');
    L.push('      # service never hits Render\'s 15 minute idle window.');
    L.push('      - key: KEEPALIVE_INTERVAL_MIN');
    L.push(`        value: ${yamlString(keepAlive)}`);
    if (publicUrl) {
        L.push('      - key: PUBLIC_URL');
        L.push(`        value: ${yamlString(publicUrl)}`);
    } else {
        L.push('      # Your service URL (https://<service>.onrender.com). Optional:');
        L.push('      # keep-alive works without it (the platform URL is detected),');
        L.push('      # but invite links need it.');
        L.push('      - key: PUBLIC_URL');
        L.push('        sync: false');
    }
    L.push('      # Secrets — set these in the Render dashboard, never in git.');
    L.push('      - key: SESSION_SECRET');
    L.push('        generateValue: true');
    L.push('      - key: GROQ_API_KEY');
    L.push('        sync: false');
    L.push('      - key: ADMIN_USERNAMES');
    L.push('        sync: false');
    L.push('      - key: INVITE_CODE');
    L.push('        sync: false');
    L.push('      - key: ADMIN_CONTACT');
    L.push(`        value: ${yamlString(adminContact)}`);
    L.push('');
    L.push('# NOTE: Render Free has an EPHEMERAL filesystem. The WhatsApp session');
    L.push('# and the user database are lost on every spin-down/restart/redeploy —');
    L.push('# attach a persistent disk and point SESSION_DIR at the mount path, or');
    L.push('# run the bot on a VPS (see deploy/autoviewer.service).');
    L.push('#');
    L.push('# Also set the GitHub secret SELF_URL = https://<service>.onrender.com');
    L.push('# so .github/workflows/keep-alive.yml can wake the service.');
    return L.join('\n');
}

/**
 * Write render.yaml.
 * @returns {{ path, changed, content }}
 */
function writeRenderConfig(opts = {}) {
    const appDir = opts.appDir || path.join(__dirname, '..');
    const file = opts.file || path.join(appDir, 'render.yaml');
    const envFile = opts.envFile || path.join(appDir, '.env');
    const existing = readExisting(file);
    const env = readEnvFile(envFile);
    const content = renderBlueprint({
        existing,
        env,
        overrides: opts.overrides || {}
    });
    const changed = !fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== content;
    if (changed && opts.write !== false) {
        fs.writeFileSync(file, content);
    }
    return { path: file, changed, content };
}

module.exports = {
    DEFAULTS,
    renderBlueprint,
    writeRenderConfig,
    readExisting,
    readEnvFile,
    yamlString
};
